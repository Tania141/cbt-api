# xlsx — два вида: пълна дата или месец + ден под общо заглавие.
from openpyxl import Workbook


def xlsx(redove):
    wb = Workbook()
    ws = wb.active
    for r in redove:
        ws.append(r)
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


