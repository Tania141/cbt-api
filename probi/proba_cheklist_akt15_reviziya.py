"""Ревизията на чеклиста за Акт 15 (26.11.2026).

Операторът: „Акт 15 събира всички документи от предишни моменти… За 15 остават
да се добавят: замервания, скица, асансьор, декларации за материали, текстовете
от проекта.“ После прегледа `ДА ПРОЧЕТА/ЧЕКЛИСТ-АКТ15-ПРЕДЛОЖЕНИЕ.md` и каза
„вписвай“. Пробата пази решеното — и че двата файла (чеклист и моменти) носят
ЕДНИ И СЪЩИ имена: сървърът ги свързва по името на реда.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
sys.stdout.reconfigure(encoding="utf-8")
from rules import cheklist_dokumenti as chd, momenti as mo

dobri, loshi = [], []


def t(ime, verno, kak=None):
    (dobri if verno else loshi).append(ime + ("" if verno else "  → %r" % (kak,)))


ok, zashto = chd.zaklyucheno()
t("чеклистът е заключен с новия отпечатък", ok, zashto)

v_cheklista = {r["dokument"] for r in chd.chetene()}
akt15 = [r["dokument"] for r in mo.redove() if r["moment"] == "Акт 15"]
p17 = [r["dokument"] for r in mo.redove() if r["moment"] == "Протокол 17"]
od = [r["dokument"] for r in mo.redove() if r["moment"] == "ОД"]

NOVI = ["Сертификат за контрол на органа за контрол", "Сертификат за акредитация на органа за контрол",
        "Протокол от контрол на съпротивление на изолация", "Протокол от контрол на защитна заземителна уредба (ЗЗУ)",
        "Протокол от контрол на мълниезащитна заземителна уредба", "Протокол от контрол на изкуствено осветление",
        "Скица на строежа, нанесен в КККР", "Договор за присъединяване към ВиК мрежите",
        "Писмо/становище за изградено СКО (сградно канализационно отклонение)",
        "Писмо/становище за изградено СВО (сградно водопроводно отклонение)",
        "Договор за присъединяване към електроразпределителната мрежа",
        "Сертификат за качество на асансьора", "Ревизионна книга на асансьора",
        "Екзекутивна документация", "Заповед по чл. 154 ЗУТ за съществено отклонение",
        "Гаранционни карти и инструкции за експлоатация"]
t("Акт 15 иска новите редове", all(n in akt15 for n in NOVI), [n for n in NOVI if n not in akt15])
t("Акт 15 — кратък (до 30 реда, беше 37)", len(akt15) <= 30, len(akt15))
t("всеки ред на Акт 15 в моментите е и в чеклиста (едно име)", all(n in v_cheklista for n in akt15),
  [n for n in akt15 if n not in v_cheklista])

MAHNATI = ["Протокол за изпълнение на достъпна среда", "Договори за строителство и строителен надзор",
           "Документи за участниците в строителството", "Документи за асансьора",
           "Декларации за експлоатационни показатели / съответствие",
           "Сертификати и протоколи за влаганите материали", "Документи за газовата инсталация",
           "Нотариално заверено пълномощно на представителя на възложителите"]
t("махнатите ги няма нито в чеклиста, нито в моментите",
  not any(n in v_cheklista or n in [r["dokument"] for r in mo.redove()] for n in MAHNATI),
  [n for n in MAHNATI if n in v_cheklista])
t("изпитванията на водопровода и канализацията — в Протокол 17",
  "Протоколи за изпитване на водопроводните инсталации" in p17
  and "Протоколи за изпитване на канализационните инсталации" in p17, p17)
t("енергийният сертификат — в окончателния доклад", any("Енергиен сертификат" in n for n in od), od)
t("геодезическото заснемане на изпълненото — в Акт 14, не в Акт 15",
  "Геодезическо заснемане на изпълнения строеж" not in akt15
  and any(r["dokument"] == "Геодезическо заснемане на изпълнения строеж" and r["moment"] == "Акт 14" for r in mo.redove()))
t("РС, ЗК, обр. 14 остават в чеклиста (събират се в своите моменти)",
  {"Разрешение за строеж", "Заповедна книга на строежа", "Акт обр. 14"} <= v_cheklista)

for x in dobri: print("  ok  " + x)
for x in loshi: print("  ЛО  " + x)
print(f"\n{len(loshi)} проблема" if loshi else f"\n{len(dobri)} проверки — Акт 15 иска само новото")
