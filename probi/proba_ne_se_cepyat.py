# -*- coding: utf-8 -*-
"""Книгите и дневниците не се цепят на документи.

Операторът, 28.10.2026: ревизионна книга от 14 страници беше записана ДЕСЕТ
пъти като отделни документи — и влиза десет пъти в описа на акт, който се
подписва.

Причината е в разделянето: указанието казва „нов документ обикновено започва
със заглавие и с номер 1 на страницата“, а ревизионната книга има заглавна
шапка на всяка страница.

Пробата пази границата: книга — един документ; серия актове обр. 7 — пак
много документа.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
sys.stdout.reconfigure(encoding="utf-8")

from rules.sloy2 import _edin_dokument_li, UKAZANIE_GRANICI

dobri, loshi = [], []


def t(ime, verno, kak=None):
    (dobri if verno else loshi).append(ime + ("" if verno else "  → %r" % (kak,)))


def chasti(*vidove):
    return [{"vid": v} for v in vidove]


# ── не се цепят ─────────────────────────────────────────────────────────────
t("ревизионна книга на много страници е ЕДИН документ",
  _edin_dokument_li(chasti(*["Ревизионна книга на пътнически асансьор"] * 10)))
t("заповедна книга — също",
  _edin_dokument_li(chasti("Заповедна книга", "Заповедна книга", "Заповедна книга")))
t("бетонов дневник — също",
  _edin_dokument_li(chasti("Бетонов дневник", "БЕТОНОВ ДНЕВНИК")))
t("технически паспорт — също",
  _edin_dokument_li(chasti("Технически паспорт на строежа", "Технически паспорт")))
t("главните букви не пречат",
  _edin_dokument_li(chasti("РЕВИЗИОННА КНИГА", "ревизионна книга")))

# ── ЦЕПЯТ СЕ — това е същината ──────────────────────────────────────────────
t("серия актове обр. 7 СЕ цепи",
  not _edin_dokument_li(chasti("Акт обр. 7", "Акт обр. 7", "Акт обр. 7")))
t("серия нотариални актове СЕ цепи",
  not _edin_dokument_li(chasti("Нотариален акт", "Нотариален акт")))
t("книга + друг документ в един файл СЕ цепи",
  not _edin_dokument_li(chasti("Ревизионна книга", "Договор за СМР")))
t("една-единствена част не задейства правилото",
  not _edin_dokument_li(chasti("Ревизионна книга")))
t("празен списък не гърми", not _edin_dokument_li([]))
t("None не гърми", not _edin_dokument_li(None))
t("части без заглавие не задействат правилото",
  not _edin_dokument_li([{"vid": ""}, {"vid": ""}]))

# ── и четецът е предупреден ─────────────────────────────────────────────────
t("указанието казва, че книгите са един документ",
  "ЕДИН документ" in UKAZANIE_GRANICI and "РЕВИЗИОННА КНИГА" in UKAZANIE_GRANICI,
  UKAZANIE_GRANICI[-300:])

for x in dobri:
    print("  ok  " + x)
for x in loshi:
    print("  ЛО  " + x)
print(("\n%d проблема" % len(loshi)) if loshi
      else ("\n%d проверки — книгите остават цели" % len(dobri)))
sys.exit(1 if loshi else 0)
