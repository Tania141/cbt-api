u"""ОБРАЗЕЦЪТ СЕ ЧЕТЕ ОТ ЗАКОНОВОТО ИМЕ, НЕ ОТ ПОРЕДНИЯ НОМЕР.

03.11.2026, от истински скан на завършен обект. Всяка страница носи горе
вдясно „Приложение № 7 към чл. 7, ал. 3, т. 7 (Образец 7)“, а в средата —
„АКТ №6“, „АКТ №12“, „АКТ №14“. Това са ПОРЕДНИТЕ номера на обекта.

Четецът взе средата: акт № 12 стана обр. 12, акт № 14 — обр. 14, акт № 15 —
обр. 15. В генерирания Акт 15 два акта обр. 7 се представиха за
„Акт Образец 14 — 2 броя“, а двайсет и четирите се разпиляха по три образеца.

Законовото наименование на образеца е отпечатано на всяка страница. То е
факт; изборът на четеца е преценка. Фактът бие преценката.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
sys.stdout.reconfigure(encoding="utf-8")

from rules.sloy2 import VIDOVE, _vid_po_zakonovo_ime

dobri, loshi = [], []


def t(ime, verno, kak=None):
    (dobri if verno else loshi).append(ime + ("" if verno else "  → %r" % (kak,)))


def vid(vid_tekst=None, naimenovanie=None, sadarzhanie=None):
    d = {"vid": vid_tekst or ""}
    if naimenovanie:
        d["naimenovanie"] = {"stoynost": naimenovanie}
    if sadarzhanie:
        d["sadarzhanie"] = {"stoynost": sadarzhanie}
    return _vid_po_zakonovo_ime(d)


# ── точно случаите от скана ─────────────────────────────────────────────────
SKAN = [
    (u"Акт №1 за приемане на извършените СМР по нива и елементи на строителната конструкция", "AKT7"),
    (u"Акт №12 за приемане на извършените СМР по нива и елементи на строителната конструкция", "AKT7"),
    (u"Акт №14 за приемане на извършените СМР по нива и елементи на строителната конструкция", "AKT7"),
    (u"Акт №18 за приемане на извършените СМР по нива и елементи на строителната конструкция", "AKT7"),
    (u"Акт №24 за приемане на извършените СМР по нива и елементи на строителната конструкция", "AKT7"),
]
for ime, chakan in SKAN:
    t(u"„%s…“ → %s" % (ime[:12], chakan), vid(ime) == chakan, vid(ime))

t(u"поредният номер НЕ определя образеца",
  all(vid(i) == "AKT7" for i, _ in SKAN), [vid(i) for i, _ in SKAN])

# ── всеки образец по законовото си име ──────────────────────────────────────
ZAKONOVI = [
    (u"Акт за установяване и съгласуване на строителния терен с одобрения и даване на основен репер", "AKT5"),
    (u"Акт за приемане на земната основа и действителните коти на извършените изкопни работи", "AKT6"),
    (u"Акт за приемане на извършените СМР по нива и елементи на строителната конструкция", "AKT7"),
    (u"Акт за установяване на всички видове СМР, подлежащи на закриване", "AKT12"),
    (u"Акт за приемане на конструкцията", "AKT14"),
    (u"Констативен акт за установяване годността за приемане на строежа", "AKT15"),
    (u"Констативен акт за установяване съответствието на строежа с издадените строителни книжа", "OBR3"),
    (u"Протокол за откриване на строителна площадка и определяне на строителна линия и ниво", "PROTOKOL2"),
    (u"Протокол за проведена 72-часова проба при експлоатационни условия", "PROTOKOL17"),
]
for ime, chakan in ZAKONOVI:
    t(u"%s се познава" % chakan, vid(ime) == chakan, vid(ime))
    t(u"%s е познат код" % chakan, chakan in VIDOVE)

# ── името се чете и от наименованието, и от съдържанието ────────────────────
t(u"и от наименованието",
  vid(u"Акт №6", naimenovanie=u"Акт за приемане на извършените СМР по нива и елементи") == "AKT7")
t(u"и от съдържанието",
  vid(u"Акт №6", sadarzhanie=u"приемане на извършените СМР по нива и елементи") == "AKT7")

# ── чуждото не се пипа ──────────────────────────────────────────────────────
for chuzhdo in (u"Разрешение за строеж", u"Нотариален акт за покупко-продажба",
                u"Договор за присъединяване към електрическа мрежа",
                u"Декларация за експлоатационни показатели", u"Скица на сграда", u""):
    t(u"„%s“ остава на четеца" % (chuzhdo[:24] or u"празно"), vid(chuzhdo) == "", vid(chuzhdo))

# Писмо, което СПОМЕНАВА образец, не е този образец — но то носи и своя вид,
# затова тук се проверява само че правилото не измисля код от нищото.
t(u"номер без законово име не дава код", vid(u"Акт №7") == "", vid(u"Акт №7"))

for x in dobri:
    print("  ok  " + x)
