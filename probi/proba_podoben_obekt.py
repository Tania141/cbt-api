def t(ime, verno, kak=None):
    (dobri if verno else loshi).append(ime + ("" if verno else "  → %r" % (kak,)))


def docx(redove, tablica=None):
    d = Document()
    for r in redove:
        bold = r.startswith("**")
        p = d.add_paragraph()
        p.add_run(r.strip("*")).bold = bold
    if tablica:
        tb = d.add_table(rows=len(tablica), cols=len(tablica[0]))
        for i, red in enumerate(tablica):
            for j, k in enumerate(red):
                tb.cell(i, j).text = k
    b = io.BytesIO()
    d.save(b)
    return b.getvalue()


def chete(raw, ime="a.docx"):
    return po.procheti(ime, base64.b64encode(raw).decode(), _vsichki_redove())


def red(rez, ime):
    return next((r for r in rez["redove"] if r["ime"] == ime), None)


