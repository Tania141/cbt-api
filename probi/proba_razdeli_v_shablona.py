# -*- coding: utf-8 -*-
"""Шаблонът на Акт 15 има място за разделите 1.1–1.5.

Операторът, 29.10.2026, даде точната подредба от свой истински акт и каза къде
стои: след „КОНСТАТИРАХМЕ“ и преди „Строежът представлява“.

Дотук шаблонът беше по образеца на Наредба № 3 — отделни стойности, без тези
раздели. Затова всичко, което системата събира и операторът сверява, нямаше
къде да влезе.

Пробата пази подредбата: раздел, който изпадне или се размести, се вижда тук, а
не в подписан документ.
"""
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
sys.stdout.reconfigure(encoding="utf-8")

from docx import Document

from cbt_docx import _spisak_ili_tochki

PAT = os.path.join(os.path.dirname(__file__), "..", "templates", "Akt_15_Template.docx")
dobri, loshi = [], []


def t(ime, verno, kak=None):
    (dobri if verno else loshi).append(ime + ("" if verno else "  → %r" % (kak,)))


P = [p.text.strip() for p in Document(PAT).paragraphs]
tekst = "\n".join(P)
redove = [x for x in P if x]


def mesto(nachalo):
    for i, x in enumerate(redove):
        if x.startswith(nachalo):
            return i
    return -1


# ── всички полета ги има ────────────────────────────────────────────────────
for pole in ("Собственост_Актове", "Актове_Протоколи", "Съответствие_Скици",
             "Договори_Мрежи", "Нива_Заверки"):
    t("шаблонът има {{%s}}" % pole, "{{%s}}" % pole in tekst)

# ── и са в правилния ред ────────────────────────────────────────────────────
i_konst = mesto("КОНСТАТИРАХМЕ")
i_teh = mesto("===ТЕХНИЧЕСКО_НАЧАЛО===")
t("КОНСТАТИРАХМЕ и техническото начало ги има", i_konst >= 0 and i_teh > i_konst,
  (i_konst, i_teh))

redica = [
    "1. По издадените строителни книжа",
    "1.1. По собствеността",
    "{{Собственост_Актове}}",
    "1.2. По законосъобразното започване",
    "1.3. Актове и протоколи",
    "{{Актове_Протоколи}}",
    "1.4. По доказване съответствието",
    "{{Съответствие_Скици}}",
    "1.5. Договори със снабдителните дружества",
    "{{Договори_Мрежи}}",
]
mesta = [mesto(x) for x in redica]
t("всички раздели са налице", all(m >= 0 for m in mesta),
  [x for x, m in zip(redica, mesta) if m < 0])
t("и вървят в този ред", mesta == sorted(mesta), list(zip(redica, mesta)))
t("всичко е МЕЖДУ „КОНСТАТИРАХМЕ“ и техническото описание",
  all(i_konst < m < i_teh for m in mesta if m >= 0),
  (i_konst, mesta, i_teh))

# ── заверките на нивата стоят СЛЕД Протокол 2, не преди ─────────────────────
i_p2 = mesto("За обекта е заверен Протокол (Образец) 2")
i_niva = mesto("{{Нива_Заверки}}")
i_p3 = mesto("За обекта е заверен Протокол (Образец) 3")
t("нивата са след Протокол 2", i_p2 >= 0 and i_niva == i_p2 + 1, (i_p2, i_niva))
t("и преди Протокол 3", i_niva < i_p3, (i_niva, i_p3))

# ── старото не е счупено ────────────────────────────────────────────────────
for pole in ("{{РС_Номер}}", "{{Проекти_Одобрени}}", "{{ЗК_Номер}}", "{{Опис_Приложения}}",
             "{{По_Изпълнение}}", "{{Възложители_Основания}}", "{{Протокол_2а_Ред}}"):
    t("старото поле %s си стои" % pole, pole in tekst)

t("техническото описание е след разделите",
  mesto("Строежът представлява") > mesto("{{Договори_Мрежи}}"))

# ── празният раздел излиза с точки, не изчезва ──────────────────────────────
t("празен раздел дава точки", _spisak_ili_tochki("").startswith("...."))
t("редовете излизат с тире",
  _spisak_ili_tochki("Акт 5\nАкт 6") == "- Акт 5\n- Акт 6",
  _spisak_ili_tochki("Акт 5\nАкт 6"))
t("празните редове се махат",
  _spisak_ili_tochki("\n\nАкт 5\n\n") == "- Акт 5")
t("None не гърми", _spisak_ili_tochki(None).startswith("...."))

for x in dobri:
    print("  ok  " + x)
for x in loshi:
    print("  ЛО  " + x)
print(("\n%d проблема" % len(loshi)) if loshi
      else ("\n%d проверки — разделите имат място" % len(dobri)))
sys.exit(1 if loshi else 0)
