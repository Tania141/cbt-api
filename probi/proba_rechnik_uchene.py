# -*- coding: utf-8 -*-
"""Речникът се учи сам — прагът на оператора: 3 обекта, 90 % (25.11.2026)."""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
sys.stdout.reconfigure(encoding="utf-8")
from rules import rechnik_uchene as ru

dobri, loshi = [], []
def t(ime, verno, kak=None):
    (dobri if verno else loshi).append(ime + ("" if verno else "  → %r" % (kak,)))

def d(pi, vid, red, sveren=True):
    return {"pi": pi, "vid": vid, "red": red, "sveren": sveren}

ZK = "Заповедна книга на строежа"
# 3 обекта, всички към един ред → научено
o = [d("a", "ЗАПОВЕДНА КНИГА", ZK), d("b", "Заповедна книга", ZK), d("c", "заповедна книга", ZK)]
r = ru.uchi(o)
t("3 обекта, 100 % → научено (главни букви и кавички не пречат)", r.get("заповедна книга", {}).get("red") == ZK, r)
t("и казва при колко обекта", r["заповедна книга"]["obekti"] == 3, r)
t("2 обекта не стигат", not ru.uchi(o[:2]), ru.uchi(o[:2]))
# броят се ОБЕКТИ: 17 акта на един обект + 1 на друг ≠ 18 доказателства
A7 = "Акт 7 и обр. 12 по част архитектура"
akt7 = [d("a", "Акт за приемане по нива и елементи", A7) for _ in range(17)] + [d("b", "Акт за приемане по нива и елементи", A7)]
t("17 акта на един обект + 1 на друг — 2 обекта, не се учи", not ru.uchi(akt7), ru.uchi(akt7))
# 90 %: 9 от 10 обекта → научено; 8 от 10 → не
devet = [d(f"o{i}", "Скица на сграда", "Скица на строежа, нанесен в КККР") for i in range(9)] + [d("o9", "Скица на сграда", "Скица от кадастралната карта")]
t("9 от 10 обекта (90 %) → научено", ru.uchi(devet).get("скица на сграда", {}).get("red") == "Скица на строежа, нанесен в КККР", ru.uchi(devet))
osem = devet[:8] + [d("o8", "Скица на сграда", "Скица от кадастралната карта"), devet[9]]
t("8 от 10 → не се учи (разделено)", not ru.uchi(osem), ru.uchi(osem))
# декларациите — разделени, не се учат
dek = [d("a", "Декларация за строителен продукт", "Декларации за бетона"), d("b", "Декларация за строителен продукт", "Сертификати за материалите"),
       d("c", "Декларация за строителен продукт", "Декларации за бетона")]
t("декларациите 2/1 — не се учат", not ru.uchi(dek))
# несверени не учат
t("несверени документи не учат", not ru.uchi([d(p, "Заповедна книга", ZK, False) for p in "abc"]))
# твоето бие броенето
t("казаното от теб („✔ това е“) не се презаписва от броенето", not ru.uchi(o, {"chetec": {"заповедна книга": {"red": "друг"}}}))
t("„не е“ забранява двойката", not ru.uchi(o, {"ne": ["заповедна книга|заповедна книга на строежа"]}))
# образците
obr = [d(p, "Акт обр. 7 за приемане", "Акт обр. 14") for p in "abc"]
t("обр. 7 никога не се учи към обр. 14", not ru.uchi(obr), ru.uchi(obr))
t("нормализацията е като в ПВА", ru.norm("„Договор“ за присъединяване, (ЕРМ)") == "договор за присъединяване ерм")
# ── стъпка 2: четецът връзва през речника ─────────────────────────────────────
ERMV = "Договор за присъединяване на обекти на клиенти към ЕРМ Запад"
DOG = "Договор за присъединяване от електроразпределителното дружество"
dok = [{"vid": ERMV, "cheklist_red": "Становище за присъединяване — електроснабдяване"},
       {"vid": "Нещо непознато", "cheklist_red": "Ред Х"}]
n = ru.prilozhi(dok, {"chetec": {ru.norm(ERMV): {"red": DOG}}})
t("казаното от теб сменя връзката на четеца", n == 1 and dok[0]["cheklist_red"] == DOG, dok[0])
t("и пази какво е избрал четецът", dok[0]["cheklist_red_chetec"] == "Становище за присъединяване — електроснабдяване", dok[0])
t("и казва откъде", dok[0]["red_ot"] == "речникът — казано от оператора", dok[0])
t("непознат вид — не се пипа", dok[1]["cheklist_red"] == "Ред Х" and "red_ot" not in dok[1], dok[1])
dok2 = [{"vid": "Заповедна книга", "cheklist_red": "Договори за строителство и строителен надзор"}]
ru.prilozhi(dok2, {"nauchen": {"заповедна книга": {"red": ZK, "obekti": 4}}})
t("наученото по броене — също, с „научено от 4 обекта“", dok2[0]["cheklist_red"] == ZK and "4 обекта" in dok2[0]["red_ot"], dok2[0])
dok3 = [{"vid": "Заповедна книга", "cheklist_red": "Х"}]
ru.prilozhi(dok3, {"nauchen": {"заповедна книга": {"red": ZK, "obekti": 4}}, "ne": ["заповедна книга|заповедна книга на строежа"]})
t("„не е“ спира и наученото", dok3[0]["cheklist_red"] == "Х", dok3[0])
dok4 = [{"vid": "Акт обр. 7", "cheklist_red": "Х"}]
ru.prilozhi(dok4, {"chetec": {"акт обр 7": {"red": "Акт обр. 14"}}})
t("различни образци — никога", dok4[0]["cheklist_red"] == "Х", dok4[0])

api = open(os.path.join(os.path.dirname(__file__), "..", "api.py"), encoding="utf-8").read()
t("адресът /api/rechnik/uchi вика ученето", "rechnik_uchene.uchi(" in api)
t("четенето (/api/sloy2/chete) връзва през речника", "rechnik_uchene.prilozhi(dokumenti" in api)

for x in dobri: print("  ok  " + x)
for x in loshi: print("  ЛО  " + x)
print(f"\n{len(loshi)} проблема" if loshi else f"\n{len(dobri)} проверки — речникът се учи по прага 3/90")
sys.exit(1 if loshi else 0)
