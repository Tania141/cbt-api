# -*- coding: utf-8 -*-
"""Връзване на ред по заглавие, когато четецът не е вързал.

Операторът, 28.10.2026: прочетено „Разрешение за строеж № 277/02.11.2023г.“
излезе с „няма ред в чеклиста“, макар редът „Разрешение за строеж“ да е бил в
списъка, подаден на четеца. Беше паднал резервният четец.

Правилото е тясно нарочно: заглавието трябва да ЗАПОЧВА с името на реда.
Съдържането не стига — „Заповед за допълване на разрешение за строеж“ съдържа
реда, но е друг документ. По-добре празно, отколкото близък ред.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
sys.stdout.reconfigure(encoding="utf-8")

from rules.sloy2 import _red_po_zaglavie, _vsichki_redove

REDOVE = _vsichki_redove()
dobri, loshi = [], []


def t(ime, verno, kak=None):
    (dobri if verno else loshi).append(ime + ("" if verno else "  → %r" % (kak,)))


def red(vid=None, nai=None):
    d = {"vid": vid or ""}
    if nai is not None:
        d["naimenovanie"] = {"stoynost": nai}
    return _red_po_zaglavie(d, REDOVE)


# ── връзва се, когато заглавието ЗАПОЧВА с реда ─────────────────────────────
r, kak = red("Разрешение за строеж № 277/02.11.2023г.")
t("разрешението за строеж се връзва", r == "Разрешение за строеж", r)
t("и казва КОЙ го е вързал", "системата" in kak, kak)

t("заповедната книга се връзва",
  red("Заповедна книга на строежа № 12")[0] == "Заповедна книга на строежа")
t("техническият паспорт се връзва",
  red("Технически паспорт на строежа")[0] == "Технически паспорт на строежа")
t("точното заглавие без нищо след него също",
  red("Разрешение за строеж")[0] == "Разрешение за строеж")

# ── НЕ се връзва, когато редът е само СПОМЕНАТ ──────────────────────────────
t("„Заповед за допълване на разрешение за строеж“ НЕ се връзва",
  red("Заповед за допълване на разрешение за строеж")[0] == "", red("Заповед за допълване на разрешение за строеж"))
t("писмо без заглавие НЕ се връзва", red("Някакво писмо")[0] == "")
t("празното заглавие не гърми и не връзва", red("")[0] == "")
t("липсващото заглавие също", _red_po_zaglavie({}, REDOVE)[0] == "")

# ── ПРИЛОЖЕНИЕ № N КЪМ ЧЛ. 7, АЛ. 3 → ОБРАЗЕЦ N ────────────────────────────
# Операторът, 28.10.2026: скан, озаглавен „Приложение № 2 към чл. 7, ал. 3,
# т. 2, (Образец 2)“, излезе с „няма ред в чеклиста“. Това е самото заглавие
# на образците по Наредба № 3 — номерът на приложението Е номерът на образеца.
r14, kak14 = red("Приложение № 14 към чл. 7, ал. 3, т. 15 (Образец 14)")
t("приложение № 14 се връзва с акт обр. 14", r14 == "Акт обр. 14", r14)
t("и казва по кое приложение", "приложение № 14" in kak14, kak14)
t("приложение № 15 се връзва с акт обр. 15",
  red("Приложение № 15 към чл. 7, ал. 3, т. 16")[0] == "Акт обр. 15")
t("номерът не се бърка: 1 не хваща 15",
  red("Приложение № 1 към чл. 7, ал. 3, т. 1")[0] == "",
  red("Приложение № 1 към чл. 7, ал. 3, т. 1"))
t("приложение към ДРУГА наредба не се връзва",
  red("Приложение № 5 към Наредба № 2")[0] == "",
  red("Приложение № 5 към Наредба № 2"))
t("приложение без ред в чеклиста остава празно",
  red("Приложение № 2 към чл. 7, ал. 3, т. 2, (Образец 2)")[0] == "",
  red("Приложение № 2 към чл. 7, ал. 3, т. 2, (Образец 2)"))
t("главните букви не пречат и тук",
  red("ПРИЛОЖЕНИЕ № 15 КЪМ ЧЛ. 7, АЛ. 3")[0] == "Акт обр. 15")

# ── наименованието също е заглавие ──────────────────────────────────────────
t("връзва се и по наименованието, когато „vid“ е късо",
  red("писмо", "Технически паспорт на строежа — част А")[0] == "Технически паспорт на строежа",
  red("писмо", "Технически паспорт на строежа — част А"))

# ── кавички и разстояния не пречат ──────────────────────────────────────────
t("кавичките не пречат",
  red("„Разрешение за строеж“ № 277")[0] == "Разрешение за строеж",
  red("„Разрешение за строеж“ № 277"))
t("двойните разстояния не пречат",
  red("Разрешение   за   строеж № 1")[0] == "Разрешение за строеж",
  red("Разрешение   за   строеж № 1"))
t("главните букви не пречат",
  red("РАЗРЕШЕНИЕ ЗА СТРОЕЖ № 277")[0] == "Разрешение за строеж",
  red("РАЗРЕШЕНИЕ ЗА СТРОЕЖ № 277"))

# ── никой измислен ред ──────────────────────────────────────────────────────
for vid in ("Разрешение за строеж № 277", "Технически паспорт на строежа", "Съгласуване на СВО"):
    r2 = red(vid)[0]
    t(f"„{vid[:28]}…“ връща ред от чеклиста или празно",
      r2 == "" or r2 in REDOVE, r2)

for x in dobri:
    print("  ok  " + x)
for x in loshi:
    print("  ЛО  " + x)
print(("\n%d проблема" % len(loshi)) if loshi
      else ("\n%d проверки — връзва се само очевидното" % len(dobri)))
sys.exit(1 if loshi else 0)
