# -*- coding: utf-8 -*-
u"""ТРИТЕ ОСИ: приложимост · наличие · приемане.

АТ, 30.10.2026: „да се разделят три различни въпроса“. Дотук състоянието беше
една ос с пет стойности и в нея се биеха три несвързани неща.

Колко струва смесването, се видя същия ден на истински линеен обект: липсващ
акт обр. 7 за фундамента на БКТП изглеждаше ТОЧНО като липсващ акт обр. 14,
който наистина не се отнася. Едното е пропуск, другото е вярно — и разликата
нямаше къде да се запише.

Пробата пази две неща: че осите казват различното различно, и че старото
състояние още се извежда от тях без разминаване.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
sys.stdout.reconfigure(encoding="utf-8")

from rules.cheklist_dokumenti import (NALICHIE, PRIEMANE, PRILOZHIMOST, osi,
                                      sastoyanie_ot_osite, spisak)

dobri, loshi = [], []


def t(ime, verno, kak=None):
    (dobri if verno else loshi).append(ime + ("" if verno else "  → %r" % (kak,)))


# ── трите речника са точно на АТ ────────────────────────────────────────────
t("приложимостта има четирите стойности",
  PRILOZHIMOST == ("изисква се", "не е приложимо", "условно приложимо", "не е поискано"),
  PRILOZHIMOST)
t("наличието има четирите стойности",
  NALICHIE == ("намерено", "липсва", "частично намерено", "не е проверено"), NALICHIE)
t("приемането има четирите стойности",
  PRIEMANE == ("потвърдено", "потвърдено с предупреждение", "отхвърлено", "в конфликт"),
  PRIEMANE)

# ── различното се казва различно ────────────────────────────────────────────
# Точно случаят от линейния обект: едното е пропуск, другото е вярно.
lipsva = osi("изисква се", "липсва")
ne_se_otnasya = osi("не е приложимо", "не е проверено", "оператор")
t("„липсва“ и „не е приложимо“ НЕ са едно и също",
  lipsva != ne_se_otnasya and lipsva["prilozhimost"] != ne_se_otnasya["prilozhimost"])
t("а и двете са различни от „условно приложимо“",
  osi("условно приложимо", "не е проверено")["prilozhimost"] not in
  (lipsva["prilozhimost"], ne_se_otnasya["prilozhimost"]))

# ── осите не приемат измислени стойности ────────────────────────────────────
for lошо in ("няма го", "налице", ""):
    try:
        osi(lошо, "липсва")
        t("непозната приложимост се отказва: %r" % lошо, False)
    except AssertionError:
        t("непозната приложимост се отказва: %r" % lошо, True)

# ── старото състояние се ИЗВЕЖДА, не се пише втори път ──────────────────────
sverka = [
    (osi("не е приложимо", "не е проверено", "условие"), "не се изисква"),
    (osi("не е приложимо", "не е проверено", "оператор"), "не се отнася"),
    (osi("условно приложимо", "не е проверено"), "за преценка"),
    (osi("изисква се", "намерено"), "налице"),
    (osi("изисква се", "намерено", "група"), "не се изисква"),
    (osi("изисква се", "частично намерено"), "не е доказано"),
    (osi("изисква се", "липсва"), "не е доказано"),
]
for o, chakano in sverka:
    t("%s · %s%s → „%s“" % (o["prilozhimost"], o["nalichie"],
                            (" · " + o["zashto"]) if o["zashto"] else "", chakano),
      sastoyanie_ot_osite(o) == chakano, sastoyanie_ot_osite(o))

# „Не се изисква“ идва от ДВЕ много различни места — затова `zashto` е нужно.
t("без „защо“ неприложимото не може да се различи",
  sastoyanie_ot_osite(osi("не е приложимо", "не е проверено"))
  != sastoyanie_ot_osite(osi("не е приложимо", "не е проверено", "оператор")))

# ── върху истинския чеклист ─────────────────────────────────────────────────
r = spisak({"вид": "сграда", "категория": "4"},
           nalichni=[{"dokument": "Разрешение за строеж", "nomer": "277"}],
           faza="od", neotnasya=["Акт обр. 14"])
t("чеклистът се чете", "greshka" not in r, r.get("greshka"))
if "greshka" not in r:
    redove = r["redove"]
    t("всеки ред носи трите оси",
      all(set(x["osi"]) == {"prilozhimost", "nalichie", "priemane", "zashto"} for x in redove))
    t("и всяко старо състояние съвпада с изведеното",
      all(x["sastoyanie"] == sastoyanie_ot_osite(x["osi"]) for x in redove),
      [x["dokument"] for x in redove if x["sastoyanie"] != sastoyanie_ot_osite(x["osi"])][:3])
    t("вписаният документ е „намерено“",
      any(x["osi"]["nalichie"] == "намерено" for x in redove))
    t("отбелязаният от оператора е „не е приложимо“ със защо „оператор“",
      any(x["osi"] == {"prilozhimost": "не е приложимо", "nalichie": "не е проверено",
                       "priemane": "", "zashto": "оператор"} for x in redove),
      [x["dokument"] for x in redove if x["osi"]["zashto"] == "оператор"])
    t("приемането още е празно — то идва от сверяването, не от чеклиста",
      all(x["osi"]["priemane"] == "" for x in redove))

for x in dobri:
    print("  ok  " + x)
for x in loshi:
    print("  ЛО  " + x)
print(("\n%d проблема" % len(loshi)) if loshi
      else ("\n%d проверки — трите оси не се смесват" % len(dobri)))
sys.exit(1 if loshi else 0)
