def grub_stroezh(project):
    p2 = doc_date(project, "protokol2")
    a14 = doc_date(project, "akt14")
    if not p2:
        return Verdict(UNKNOWN, "Още няма дата на съставяне на Протокол 2.")
    if not a14:
        return Verdict(UNKNOWN, "Още няма дата на Акт 14 — грубият строеж не е доказан.")
    lineen = (project.get("vid") or "sgrada").startswith("lineen")
    godini = 10 if lineen else 5
    krai = years_after(p2, godini)
    kakvo = "техническа инфраструктура" if lineen else "сграда"
    if a14 <= krai:
        return Verdict(OK, f"Грубият строеж е завършен в срок ({kakvo}, {godini} г.) — "
                           f"Акт 14 от {a14.strftime('%d.%m.%Y')}, краен срок {krai.strftime('%d.%m.%Y')}.")
    return Verdict(WARN, f"Акт 14 е от {a14.strftime('%d.%m.%Y')}, а {godini}-годишният срок за груб строеж "
                         f"({kakvo}) е изтекъл на {krai.strftime('%d.%m.%Y')} — "
                         f"просрочие с {(a14 - krai).days} дни.")


