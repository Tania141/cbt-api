"""Категорията на строежа — твърдението срещу разпоредбата.

КОГА се прави проверката: ПРЕДИ разрешението за строеж.

ОСИП предхожда РС — той е основанието, върху което РС се издава. Значи при
ОСИП няма РС, срещу който да се сверява; там категорията е ТВЪРДЕНИЕ НА
НАДЗОРА, обосновано с Наредба № 1 и чл. 137 ЗУТ. Одобряващият орган я
потвърждава после, в РС.

Затова проверката е тук — където грешката още може да се поправи, преди внасяне.

K1 не чете наредбата: сверява самото твърдение със себе си (дума, член, паспорт).
K2 чете наредбата и проверява съществува ли цитираната разпоредба.
Смисловата проверка — попада ли обектът в текста на разпоредбата — е за AI и
чака слой 2 на ОСИП.
"""
import re
from .engine import rule, Verdict, OK, WARN, UNKNOWN
from .naredba1 import Naredba, pragove

# Член от Наредба № 1 → коя категория определя
CHLEN_KAT = {2: 1, 4: 2, 6: 3, 8: 4, 10: 5}
DUMA_KAT = {"първа": 1, "втора": 2, "трета": 3, "четвърта": 4, "пета": 5}
KAT_DUMA = {v: k for k, v in DUMA_KAT.items()}


def cheti_citat(text):
    """Изважда категорията и цитатите от свободния текст на раздел А."""
    t = re.sub(r"\s+", " ", text or "")
    d = {}
    m = re.search(r"\b(първа|втора|трета|четвърта|пета)\s+КАТЕГОРИЯ", t, re.IGNORECASE)
    if m:
        d["duma"] = DUMA_KAT[m.group(1).lower()]
    # Наредба № 1 — чл. N, ал. M, [буква], т. K
    m = re.search(r"чл\.\s*(\d+)\s*,\s*ал\.\s*(\d+)(?:[^.]{0,40}?т\.\s*(\d+))?", t)
    if m:
        d["chl"], d["al"] = int(m.group(1)), int(m.group(2))
        if m.group(3):
            d["t"] = int(m.group(3))
    # ЗУТ — чл. 137, ал. 1, т. K
    m = re.search(r"чл\.\s*137\s*,\s*ал\.\s*1\s*,\s*т\.\s*(\d+)", t)
    if m:
        d["zut_t"] = int(m.group(1))
    return d


def _p(text, kategoria=None):
    p = {"osip": {"kategoria": text}}
    if kategoria:
        p["kategoria"] = kategoria
    return p


from .realni import IST_RING as R_IST, GURMAZOVO as R_GUR, izmeni

# Дословните цитати от докладите — четат се от реалните обекти, не се преписват.
IST_RING = R_IST["osip"]["kategoria"]
GURMAZOVO = R_GUR["osip"]["kategoria"]


@rule(
    code="K1",
    title="Категорията съвпада с цитираните разпоредби",
    citation="Наредба № 1 от 30.07.2003 г.: чл. 2 определя първа категория, чл. 4 — втора, "
             "чл. 6 — трета, чл. 8 — четвърта, чл. 10 — пета. ЗУТ, чл. 137, ал. 1: т. 1 е "
             "първа категория, т. 2 — втора, т. 3 — трета, т. 4 — четвърта, т. 5 — пета.",
    what="Категорията, изписана с думи в раздел А, трябва да съвпада с члена от Наредба № 1 "
         "и с точката от чл. 137 ЗУТ, които са цитирани до нея — и с категорията в паспорта. "
         "Проверката е чиста аритметика върху номерата; не чете наредбата.",
    cases=[
        ("ИСТ РИНГ — думата казва втора, цитатите сочат трета", R_IST, WARN),
        ("ГУРМАЗОВО — пета навсякъде, включително в паспорта", R_GUR, OK),
        ("ГУРМАЗОВО с грешна категория в паспорта", izmeni(R_GUR, kategoria="3"), WARN),
        ("няма цитат", _p("пета категория"), UNKNOWN),
    ],
)
def kategoria_saglasuvanost(project):
    d = cheti_citat((project.get("osip") or {}).get("kategoria"))
    tvardeniya = {}
    if "duma" in d:
        tvardeniya["изписаното с думи"] = d["duma"]
    if "chl" in d and d["chl"] in CHLEN_KAT:
        tvardeniya[f"чл. {d['chl']} от Наредба № 1"] = CHLEN_KAT[d["chl"]]
    if "zut_t" in d and d["zut_t"] in KAT_DUMA:
        tvardeniya[f"чл. 137, ал. 1, т. {d['zut_t']} ЗУТ"] = d["zut_t"]
    pas = str(project.get("kategoria") or "").strip()
    if pas.isdigit():
        tvardeniya["паспортът"] = int(pas)

    if len(tvardeniya) < 2:
        return Verdict(UNKNOWN, "В раздел А няма достатъчно данни — трябват категорията с думи "
                                "и поне един цитат (чл. от Наредба № 1 или чл. 137 ЗУТ).")
    stojnosti = set(tvardeniya.values())
    if len(stojnosti) == 1:
        k = stojnosti.pop()
        return Verdict(OK, f"{KAT_DUMA[k]} категория — съгласувано на {len(tvardeniya)} места.")
    opis = "; ".join(f"{k} → {KAT_DUMA.get(v, v)}" for k, v in tvardeniya.items())
    return Verdict(WARN, "Категорията се разминава между източниците: " + opis +
                         ". Категорията определя целия изискван набор документи — "
                         "разминаването трябва да се затвори преди внасяне.")


@rule(
    code="K3",
    title="ОСИП предхожда разрешението за строеж",
    citation="чл. 142, ал. 6, т. 2 ЗУТ — инвестиционните проекти се одобряват въз основа на "
             "оценка за съответствието, извършена от консултант; чл. 148 ЗУТ — разрешението "
             "за строеж се издава след одобряване на проекта.",
    what="Оценката на съответствието е ОСНОВАНИЕТО, върху което се издава разрешението за "
         "строеж. Дата на доклада след датата на разрешението означава или сгрешена дата, "
         "или доклад по изменение, който трябва да се води отделно.",
    cases=[
        ("ГУРМАЗОВО с получено разрешение — докладът го предхожда",
         izmeni(R_GUR, **{"РС_Дата": "18.06.2026"}), OK),
        ("същият обект, разрешение отпреди доклада",
         izmeni(R_GUR, **{"РС_Дата": "10.05.2026"}), WARN),
        ("ГУРМАЗОВО както е днес — още няма разрешение", R_GUR, UNKNOWN),
        ("ИСТ РИНГ — докладът от 28.10.2025 предхожда разрешение от 15.12.2025",
         izmeni(R_IST, **{"РС_Дата": "15.12.2025"}), OK),
    ],
)
def osip_predhozhda_rs(project):
    from .engine import parse_date
    osip = parse_date((project.get("osip") or {}).get("izh_data"))
    rs = parse_date(project.get("РС_Дата"))
    if not osip:
        return Verdict(UNKNOWN, "Докладът за оценка на съответствието още няма изходяща дата.")
    if not rs:
        return Verdict(UNKNOWN, "Още няма разрешение за строеж — обектът е в проектна фаза.")
    if osip <= rs:
        return Verdict(OK, f"Докладът ({osip.strftime('%d.%m.%Y')}) предхожда разрешението "
                           f"({rs.strftime('%d.%m.%Y')}) — както изисква редът.")
    return Verdict(WARN, f"Докладът е от {osip.strftime('%d.%m.%Y')}, а разрешението за строеж — "
                         f"от {rs.strftime('%d.%m.%Y')}. Оценката на съответствието е основанието "
                         f"за издаване на разрешението, значи не може да е след него. "
                         f"Или датата е сгрешена, или това е доклад по изменение.")


@rule(
    code="K2",
    title="Цитираната разпоредба съществува и какви прагове поставя",
    citation="Наредба № 1 от 30 юли 2003 г. за номенклатурата на видовете строежи — "
             "заключена с отпечатък в rules/naredba1.lock.json.",
    what="Намира цитираната разпоредба в самата наредба. Ако чл./ал./т. не съществуват, "
         "цитатът е грешен — това хваща копи-пейст грешките. Показва и числовите прагове, "
         "които разпоредбата поставя (kV, кв. м, места, работни места), за да се сверят "
         "с данните на обекта.",
    cases=[
        ("ИСТ РИНГ — чл. 6, ал. 2, т. 6 съществува", R_IST, OK),
        ("ГУРМАЗОВО — чл. 10, ал. 1 съществува", R_GUR, OK),
        ("несъществуваща точка",
         _p("трета КАТЕГОРИЯ, съгласно чл. 6, ал. 2, т. 99 от Наредба № 1"), WARN),
        ("несъществуващ член",
         _p("трета КАТЕГОРИЯ, съгласно чл. 99, ал. 1, т. 1 от Наредба № 1"), WARN),
        ("няма цитат", _p("пета категория"), UNKNOWN),
    ],
)
def citat_sashtestvuva(project):
    d = cheti_citat((project.get("osip") or {}).get("kategoria"))
    if "chl" not in d:
        return Verdict(UNKNOWN, "В раздел А няма цитат от Наредба № 1 (чл., ал.).")
    n = Naredba()
    if not n.ok:
        return Verdict(UNKNOWN, n.prichina)
    r, err = n.razporedba(d["chl"], d["al"], d.get("t"))
    if err:
        return Verdict(WARN, f"Цитатът сочи разпоредба, която не съществува: {err}")
    tekst = (r["zaglavie"] or "") + " " + (r["tochka"] or "")
    pr = pragove(tekst)
    kade = f"чл. {d['chl']}, ал. {d['al']}" + (f", т. {d['t']}" if "t" in d else "")
    if pr:
        opis = "; ".join(f"{p['kakvo']} — {p['tekst']}" for p in pr[:4])
        return Verdict(OK, f"{kade} съществува. Поставя прагове: {opis}. "
                           f"Сверете ги с данните на обекта.")
    return Verdict(OK, f"{kade} съществува. Разпоредбата не поставя числови прагове — "
                       f"съответствието е по вид на строежа.")
