def zakliuchena():
    """(ok, причина) — сверена ли е таблицата срещу текста на наредбата."""
    if not os.path.isfile(LOCK):
        return False, ("Наредба № 7 не е сверена — липсва naredba7.lock.json. "
                       "Пусни: python tools/pin_naredba.py --pin")
    d = json.load(open(LOCK, encoding="utf-8"))
    if d.get("zoni") != sorted(ZONI):
        return False, "Таблицата с зони е променена след последната сверка."
    if not d.get("sverena"):
        return False, "Отпечатъкът е записан без успешна сверка срещу текста."
    return True, None


def sveri(text):
    """Всеки израз от таблицата да се намира в текста. Връща липсващите."""
    lipsvat = []
    for zona, izrazi in IZRAZI.items():
        for iz in izrazi:
            if iz not in text:
                lipsvat.append(f"{zona}: „{iz}“ не се намира в наредбата")
    return lipsvat


def diapazon(zona, pokazatel):
    z = ZONI.get(zona)
    return (z[pokazatel], z["chl"], z["ime"]) if z else (None, None, None)


def opis(granici, edinica="%"):
    lo, hi = granici
    if lo is None:
        return f"до {hi}{edinica}"
    if hi is None:
        return f"най-малко {lo}{edinica}"
    return f"от {lo} до {hi}{edinica}"
