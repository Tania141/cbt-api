def selftest():
    """Проверява твърдения, които биха се счупили тихо при редакция."""
    greshki = []

    sgrada = {"vid": "сграда", "kategoria": "3", "faza": "технически",
              "povod": "ново", "spo": [], "zashtitena": False,
              "pametnik": False, "opasni": False}
    lineen = {**sgrada, "vid": "линеен"}

    for t, tekst, izt, sast in doklad(sgrada):
        if sast == "текст" and not izt:
            greshki.append(f"{t['kod']}: текст без източник")

    # сеизмичното изречение — само при сгради
    t169 = [x for x in doklad(sgrada) if x[0]["kod"] == "169_1_1"][0]
    if "сеизмичните" not in (t169[1] or ""):
        greshki.append("169_1_1: липсва сеизмичното изречение при сграда")
    l169 = [x for x in doklad(lineen) if x[0]["kod"] == "169_1_1"][0]
    if "сеизмичните" in (l169[1] or ""):
        greshki.append("169_1_1: сеизмичното изречение не бива при линеен обект")

    # становището от РСПБЗН — по категория
    t2 = [x for x in doklad(sgrada) if x[0]["kod"] == "169_1_2"][0]
    if "РСПБЗН" not in (t2[1] or ""):
        greshki.append("169_1_2: трета категория иска становище от РСПБЗН")
    t2_peta = [x for x in doklad({**sgrada, "kategoria": "5"})
               if x[0]["kod"] == "169_1_2"][0]
    if "РСПБЗН" in (t2_peta[1] or ""):
        greshki.append("169_1_2: пета категория не иска становище от РСПБЗН")

    # Неприложимото се КАЗВА, не се премълчава — решение на оператора.
    # Тестът пази точно това: точката да излиза с текст, а не празна.
    for kod, pr, kakvo in (("169_3_2", sgrada, "бедствията при сграда"),
                           ("169_1_6", lineen, "енергията при линеен обект")):
        red = [x for x in doklad(pr) if x[0]["kod"] == kod][0]
        if red[1] != NEPRILOZHIMO:
            greshki.append(f"{kod}: {kakvo} трябва да излиза като неприложимо")

    # СПО — списъкът се изброява
    spo = [x for x in doklad({**sgrada, "spo": ["асансьорна уредба"]})
           if x[0]["kod"] == "142_5_6"][0]
    if "асансьорна уредба" not in (spo[1] or ""):
        greshki.append("142_5_6: съоръженията трябва да се изброяват")

    # ПУП — от паспорта, и липсата му си личи
    bez_pup = [x for x in doklad(sgrada) if x[0]["kod"] == "142_5_1"][0]
    if bez_pup[3] != "липсва":
        greshki.append("142_5_1: без данни за ПУП точката трябва да личи като липсваща")
    s_pup = [x for x in doklad({**sgrada, "pup": "Решение на СОС № 50/30.03.2001 г.",
                                "kadastr": "Заповед № РД-18-108/13.12.2016 г."})
             if x[0]["kod"] == "142_5_1"][0]
    if "Решение на СОС" not in (s_pup[1] or "") or "кадастралната карта" not in (s_pup[1] or ""):
        greshki.append("142_5_1: текстът трябва да носи ПУП-а и кадастралната карта")

    return greshki


