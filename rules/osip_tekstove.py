# ── Сглобяване ───────────────────────────────────────────────────────────────

def _dopalni_rspbzn(tekst, priznaci):
    """Становището от РСПБЗН е задължително за 1, 2 и 3 категория."""
    if str(priznaci.get("kategoria", "")) not in KATEGORII_S_RSPBZN:
        return tekst
    stanovishte = str(priznaci.get("rspbzn", "")).strip()
    dopalnenie = (f" За проекта е издадено становище от {stanovishte} за "
                  f"съответствие на инвестиционните проекти с нормите на пожарна "
                  f"безопасност." if stanovishte else
                  " За проекта се изисква становище от РСПБЗН за съответствие на "
                  "инвестиционните проекти с нормите на пожарна безопасност.")
    return tekst + dopalnenie


def _tekst_spo(priznaci):
    """Текстът за съоръженията с повишена опасност, когато такива има.

    Изброяват се самите съоръжения, защото проверката по чл. 142, ал. 5, т. 6
    не е „има ли асансьор“, а обхваща цяло приложение от видове — котли, съдове
    под налягане, газови уредби, повдигателни съоръжения, въжени линии.
    """
    spo = [str(x).strip() for x in (priznaci.get("spo") or []) if str(x).strip()]
    if not spo:
        return None
    izbroyavane = ", ".join(spo)
    return (f"В проекта са предвидени съоръжения с повишена опасност: "
            f"{izbroyavane}. Съоръженията подлежат на технически надзор по реда "
            f"на Закона за техническите изисквания към продуктите и приложимата "
            f"наредба за съответния вид.")


def _tekst_pup(priznaci):
    """Съответствието с ПУП при ново строителство.

    Тук няма готова формулировка: текстът сочи с какво е одобрен планът, а това
    е различно за всеки обект. Идва от паспорта. Празно поле значи, че точката
    остава незапълнена — вижда се, вместо да се пише общо изречение, което не
    доказва нищо.
    """
    pup = str(priznaci.get("pup", "")).strip()
    if not pup:
        return None
    tekst = ("Строежът е проектиран в съответствие с предвижданията на подробния "
             f"устройствен план, одобрен с {pup}")
    kadastr = str(priznaci.get("kadastr", "")).strip()
    if kadastr:
        tekst += f", и с кадастралната карта, одобрена със {kadastr}"
    return tekst + "."


def otgovor(tochka, priznaci):
    """Какво излиза за тази точка. Връща (текст, източник, състояние).

    състояние: „текст“ · „пропуска се“ · „липсва“
    """
    p = dict(priznaci)
    p["spo_ima"] = bool(p.get("spo"))

    if tochka["kod"] == "142_5_6" and p["spo_ima"]:
        return _tekst_spo(p), "сглобено от списъка на съоръженията", "текст"

    if tochka["kod"] == "142_5_1" and p.get("povod") != "преработка_154":
        tekst = _tekst_pup(p)
        if tekst:
            return tekst, "сглобено от паспорта — ПУП и кадастрална карта", "текст"

    for uslovie, tekst, iztochnik in tochka["otgovori"]:
        if all(p.get(k) == v for k, v in uslovie.items()):
            if tekst is None:
                return None, iztochnik, "пропуска се"
            if tochka["kod"] == "169_1_2":
                tekst = _dopalni_rspbzn(tekst, p)
            return tekst, iztochnik, "текст"
    return None, None, "липсва"


def doklad(priznaci):
    """Всички точки за този обект, в реда на доклада."""
    return [(t, *otgovor(t, priznaci)) for t in TOCHKI]


