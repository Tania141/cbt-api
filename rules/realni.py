def izmeni(obekt, **promeni):
    """Копие на реален обект с променени данни — за случаите с ⚠️.

    Формата, имената и останалите стойности остават истински; сменя се едно
    число. Така предупреждаващият път се доказва, без да се измислят обекти.
    """
    o = copy.deepcopy(obekt)
    for k, v in promeni.items():
        if isinstance(v, dict) and isinstance(o.get(k), dict):
            o[k] = {**o[k], **v}
        else:
            o[k] = v
    return o


def bez(obekt, *kliuchove):
    """Копие на реален обект БЕЗ дадени дати — за случаите „още няма…“.

    Отделен помощник, защото `izmeni` слива речниците: подаване на по-малък
    docDates не маха нищо.
    """
    o = copy.deepcopy(obekt)
    o["docDates"] = {k: v for k, v in (o.get("docDates") or {}).items()
                     if k not in kliuchove}
    return o


