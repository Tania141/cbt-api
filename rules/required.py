"""Изискваният набор документи.

Кои документи изобщо се изискват зависи от четири неща:

  1. КАТЕГОРИЯТА на строежа — определя се по Наредба № 1/30.07.2003 г. за
     номенклатурата на видовете строежи и по чл. 137 ЗУТ, и е ВПИСАНА В
     РАЗРЕШЕНИЕТО ЗА СТРОЕЖ. Не се преценява от оператора — преписва се.
  2. ВИДЪТ на строежа — сграда, линеен обект, или линеен с КТП.
  3. НАСТЪПИЛО СЪБИТИЕ — спиране, продължаване, щети, поискано изпитване.
  4. НАЛИЧИЕ — машини и съоръжения, преход към метална конструкция.

Най-опасното тук не е системата да пропусне документ, а да ИСКА НЕСЪЩЕСТВУВАЩ.
Ако тя настоява за Акт 13 на строеж, който не е претърпял бедствие, операторът
се научава да пренебрегва предупрежденията — и тогава пропуска истинското.
Затова документите по събитие не се изискват никога автоматично.
"""
from .engine import rule, Verdict, OK, WARN, UNKNOWN

VSICHKI = {1, 2, 3, 4, 5}
PARVI_TRI = {1, 2, 3}

# Категориите са по таблицата на оператора, сверена с чл. 177, ал. 2 ЗУТ:
# строежите от първа, втора и трета категория се въвеждат в експлоатация въз
# основа на разрешение за ползване — оттам и „Акт 16: 1–3“.
NABOR = [
    # ключ          заглавие                              категории    условие
    ("protokol1",  "Протокол 1 — предаване на проект и РС", VSICHKI,   None),
    ("protokol2",  "Протокол 2 / 2а",                       VSICHKI,   None),
    ("zk_zaverka", "Заповедна книга — заверка",             VSICHKI,   None),
    ("obrazec3",   "Констативен акт обр. 3",                VSICHKI,   None),
    ("akt5",       "Акт 5",                                 PARVI_TRI, None),
    ("akt6",       "Акт 6",                                 PARVI_TRI, None),
    # Протокол 17 е ограничен до 1–3 категория, но и там се съставя ПО ПОИСКВАНЕ —
    # затова стои и в PO_SABITIE и никога не се изисква автоматично.
    ("protokol17", "Протокол 17 — 72-часова проба",         PARVI_TRI, "po_poiskvane"),
    ("akt7",       "Акт 7",                                 VSICHKI,   None),
    ("akt8",       "Акт 8 — фундаменти за монтаж",           VSICHKI,   "montazh"),
    ("akt9",       "Акт 9 — машини и съоръжения",            VSICHKI,   "mashini"),
    ("akt12",      "Акт 12 — скрити работи",                 VSICHKI,   None),
    ("akt14",      "Акт 14 — приемане на конструкцията",     VSICHKI,   None),
    ("akt15",      "Акт 15",                                 VSICHKI,   None),
    ("akt16",      "Акт 16 — ДПК",                           PARVI_TRI, None),
    ("doklad",     "Окончателен доклад",                     VSICHKI,   None),
    ("osip",       "ОСИП",                                   VSICHKI,   None),
]

# Никога не се изискват автоматично — само при настъпило събитие или по поискване.
#
# Акт 13 (щети от непреодолима сила) НЕ е тук и не е никъде другаде: по решение
# на оператора от 02.09 той отпада от системата. Съставя се рядко, операторът не
# е свикнал с него, и един акт на ръка е по-евтин от постоянно присъствие в
# списъци, което не носи полза. Шаблонът и ключът в бекенда остават — махнат е
# само от изборите пред оператора.
PO_SABITIE = {
    "akt10":      "Акт 10 — спиране на строителството",
    "akt11":      "Акт 11 — продължаване",
    "protokol17": "Протокол 17 — 72-часова проба (при поискване)",
}


def _uslovie_izpalneno(project, cond):
    if cond is None:
        return True
    if cond == "mashini":
        return bool(project.get("imaMashini"))
    if cond == "montazh":
        return bool(project.get("imaMashini")) or bool(project.get("metalnaKonstrukcia"))
    if cond == "po_poiskvane":
        return False        # никога не се изисква само по себе си
    return True


def iziskvani(project):
    """Кои документи се изискват за този строеж. Връща [(ключ, заглавие)]."""
    try:
        kat = int(str(project.get("kategoria") or "").strip())
    except ValueError:
        return None
    if kat not in VSICHKI:
        return None
    return [(k, t) for k, t, kats, cond in NABOR
            if kat in kats and _uslovie_izpalneno(project, cond)]


def _vpisan(project, key):
    return bool((project.get("docDates") or {}).get(key))


def _p(**kw):
    d = {"docDates": kw.pop("docDates", {})}
    d.update(kw)
    return d


from .realni import DENKA, izmeni

# Пълният набор — реалните дати на Денка, допълнени с документите, които
# окончателният доклад не изброява поименно.
_PALEN = {**DENKA["docDates"], "protokol1": "10.03.2022", "osip": "20.11.2021",
          "akt15": "10.04.2025", "akt16": "25.04.2025"}


def _denka(**promeni):
    return izmeni(DENKA, docDates={**_PALEN, **promeni})


@rule(
    code="S1",
    title="Пълнота на набора според категорията",
    citation="чл. 168, ал. 1, т. 2 ЗУТ — лицето, упражняващо строителен надзор, носи отговорност "
             "за осъществяване на контрол относно пълнота и правилно съставяне на актовете и "
             "протоколите по време на строителството. Категорията се определя по Наредба № 1 "
             "от 30.07.2003 г. и чл. 137 ЗУТ и е вписана в разрешението за строеж.",
    what="Проверява кои документи се изискват за тази категория и вид строеж и кои от тях "
         "още не са вписани в регистъра. Документите по събитие — Акт 10, 11, 13 и "
         "Протокол 17 — не се изискват никога автоматично.",
    cases=[
        ("ДЕНКА — трета категория, наборът е пълен", _denka(), OK),
        ("същият обект без Акт 16 — при трета категория се изисква",
         izmeni(DENKA, docDates={k: v for k, v in _PALEN.items() if k != "akt16"}), WARN),
        ("същите документи при пета категория — Акт 5, 6 и 16 не се искат",
         izmeni(_denka(), kategoria="5"), OK),
        ("ДЕНКА с машини, но без Акт 8 и 9",
         izmeni(_denka(), imaMashini=True), WARN),
        ("категорията не е посочена", izmeni(_denka(), kategoria=""), UNKNOWN),
    ],
)
def nabor_pylnota(project):
    iz = iziskvani(project)
    if iz is None:
        return Verdict(UNKNOWN, "Категорията на строежа не е посочена — не може да се определи "
                                "кои документи се изискват. Тя е вписана в разрешението за строеж.")
    lipsvat = [t for k, t in iz if not _vpisan(project, k)]
    kat = int(project["kategoria"])
    if not lipsvat:
        return Verdict(OK, f"Наборът за {kat}. категория е пълен — {len(iz)} документа.")
    return Verdict(WARN, f"За {kat}. категория липсват {len(lipsvat)} от {len(iz)}: "
                         + ", ".join(lipsvat) + ".")


@rule(
    code="S2",
    title="Вписан документ, който за тази категория не се изисква",
    citation="Наредба № 1 от 30.07.2003 г. и чл. 137 ЗУТ — категорията определя обхвата "
             "на задължителните актове и протоколи.",
    what="Обратната проверка: документ, вписан в регистъра, но неизискван за категорията. "
         "Не е грешка — може да е съставен по преценка — но си струва да се погледне, "
         "защото често е признак за сбъркана категория.",
    cases=[
        ("ДЕНКА — трета категория, Акт 5, 6 и 16 са на място", _denka(), OK),
        ("същите документи, но обявени за пета категория",
         izmeni(_denka(), kategoria="5"), WARN),
        ("Акт 10 при спиране — по събитие, не се брои за излишен", _denka(), OK),
        ("Протокол 17 при пета категория — там не се изисква",
         izmeni(_denka(protokol17="05.05.2025"), kategoria="5"), WARN),
    ],
)
def nabor_izlishni(project):
    if iziskvani(project) is None:
        return Verdict(UNKNOWN, "Категорията на строежа не е посочена.")
    kat = int(project["kategoria"])
    # Съди се по КАТЕГОРИЯ, не по условията. Акт 9 без отметнати машини не е
    # излишен — просто условието още не е обявено; да се вика за него е шум.
    izlishni = [t for k, t, kats, _ in NABOR
                if kat not in kats and _vpisan(project, k)]
    if not izlishni:
        return Verdict(OK, f"Няма вписани документи извън набора за {kat}. категория.")
    return Verdict(WARN, f"Вписани, но неизисквани за {kat}. категория: " + ", ".join(izlishni) +
                         ". Проверете дали категорията е вярна — тя е вписана в разрешението за строеж.")
